function b(
  id: string,
  property: Property,
  guest: string,
  email: string,
  phone: string,
  checkIn: string,
  checkOut: string,
  rooms: { roomId: string; roomName: string; quantity: number; pricePerNight: number }[],
  paymentMethod: string,
  overrides: Partial<Booking> = {},
): Booking {
  const nights = Math.round(
    (new Date(checkOut).getTime() - new Date(checkIn).getTime()) / 86400000,
  );
  const subtotal = rooms.reduce((sum, r) => sum + r.pricePerNight * r.quantity * nights, 0);
  const fees = Math.round(subtotal * DEMO_FEES_RATE);
  const total = subtotal + fees;
  const commissionAmount = Math.round(subtotal * property.commissionRate);
  return {
    id,
    propertyId: property.id,
    propertySlug: property.slug,
    propertyName: property.name,
    propertyLocation: property.location,
    ownerId: property.ownerId,
    guestName: guest,
    guestEmail: email,
    guestPhone: phone,
    checkIn,
    checkOut,
    nights,
    rooms,
    subtotal,
    fees,
    total,
    commissionRate: property.commissionRate,
    commissionAmount,
    propertyShare: subtotal - commissionAmount,
    status: "confirmed",
    paymentStatus: "paid",
    paymentMethod,
    settlementStatus: "pending",
    createdAt: checkIn,
    ...overrides,
  };
}

